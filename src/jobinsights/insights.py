"""Market insights computed from the extracted fields: what skills pay, who sponsors, what to learn.

Everything here reads the dashboard table (`jobinsights report`) and returns plain numbers, so the
findings in the README and docs are regenerated by one command rather than typed. Pay results come
from postings that state a salary, which are not a random sample, and all pay comparisons are
associations (adjusted for role, experience and work arrangement), not causal effects.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from . import config
from .taxonomy import FAMILY

OUT_DIR = config.DATA_DIR.parent / "outputs"
INSIGHTS_JSON = OUT_DIR / "insights.json"
DATA_ROLES = ("Data Analyst", "Data Scientist", "Data Engineer", "AI/ML Engineer")
TECH_ROLES = DATA_ROLES + ("Software Engineer",)
ENTRY_LEVELS = ("Entry level", "Associate", "Internship")
SENIOR_LEVELS = ("Mid-Senior level", "Director", "Executive")
TECHNICAL_FAMILIES = frozenset({"Programming", "Data & ML", "BI", "Databases", "Cloud & DevOps"})
MIN_SALARY, MAX_SALARY = 15_000.0, 600_000.0


def hard_skills(skills) -> list[str]:
    """Technical skills only: boilerplate-prone business and soft skills would add noise."""
    return [s for s in skills if FAMILY.get(s) in TECHNICAL_FAMILIES]


def skill_matrix(series: pd.Series, names: list[str]) -> np.ndarray:
    """Boolean postings x skills matrix for the given skill names."""
    col = {n: i for i, n in enumerate(names)}
    m = np.zeros((len(series), len(names)), dtype=bool)
    for r, skills in enumerate(series):
        for s in skills:
            j = col.get(s)
            if j is not None:
                m[r, j] = True
    return m


def skill_demand(df: pd.DataFrame, role: str, top: int = 15) -> pd.DataFrame:
    """Share of a role's postings that mention each hard skill, by seniority group."""
    sub = df[df["role"] == role]
    groups = {
        "all": sub,
        "entry": sub[sub["formatted_experience_level"].isin(ENTRY_LEVELS)],
        "senior": sub[sub["formatted_experience_level"].isin(SENIOR_LEVELS)],
    }
    rows = []
    for name, g in groups.items():
        exploded = g["skills_rules"].map(hard_skills).explode().dropna()
        share = exploded.value_counts() / max(len(g), 1)
        rows.append(share.rename(name))
    out = pd.concat(rows, axis=1).fillna(0.0)
    out["n_all"], out["n_entry"], out["n_senior"] = (len(groups[k]) for k in groups)
    return out.sort_values("all", ascending=False).head(top)


ARRANGEMENTS = ("remote", "hybrid", "onsite")  # "unknown" is the baseline


def _design(s: pd.DataFrame, names: list[str], sk: np.ndarray | None = None):
    """Design matrix: intercept, role, experience level, work arrangement, skill indicators."""
    if sk is None:
        sk = skill_matrix(s["skills_rules"].map(hard_skills), names)
    cols = [np.ones(len(s))]
    labels = ["intercept"]
    for prefix, series in (
        ("role", s["role"]),
        ("exp", s["formatted_experience_level"].fillna("Unknown")),
    ):
        dummies = pd.get_dummies(series, prefix=prefix, drop_first=True)
        cols += [dummies[c].to_numpy(float) for c in dummies]
        labels += list(dummies.columns)
    for arrangement in ARRANGEMENTS:
        cols.append((s["remote_rules"] == arrangement).to_numpy(float))
        labels.append(f"arr_{arrangement}")
    return np.column_stack([*cols, sk.astype(float)]), labels + list(names)


def skill_premiums(
    df: pd.DataFrame,
    roles: tuple[str, ...] = TECH_ROLES,
    min_n: int = 40,
    n_boot: int = 300,
    seed: int = 0,
) -> dict:
    """Adjusted pay association of each skill among tech postings that state pay.

    log(annual pay) ~ role + experience level + work arrangement + one indicator per skill, fit by
    least squares. Confidence intervals resample companies (not postings) with replacement because
    one company often posts the same role many times.
    """
    s = df[df["role"].isin(roles) & df["salary_mid"].between(MIN_SALARY, MAX_SALARY)].reset_index(
        drop=True
    )
    skills_all = s["skills_rules"].map(hard_skills)
    counts = skills_all.explode().value_counts()
    names = sorted(counts[counts >= min_n].index)
    sk = skill_matrix(skills_all, names)

    X, labels = _design(s, names, sk)
    y = np.log(s["salary_mid"].to_numpy(float))

    def fit(rows: np.ndarray) -> np.ndarray:
        return np.linalg.lstsq(X[rows], y[rows], rcond=None)[0]

    coef = fit(np.arange(len(s)))
    pred = X @ coef
    r2 = 1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum()

    company = s["company_name"].fillna("").where(s["company_name"].fillna("") != "", s["job_id"])
    groups = [g.to_numpy() for _, g in s.groupby(company).groups.items()]
    rng = np.random.default_rng(seed)
    boots = np.empty((n_boot, X.shape[1]))
    for b in range(n_boot):
        pick = rng.integers(0, len(groups), len(groups))
        boots[b] = fit(np.concatenate([groups[i] for i in pick]))

    def pct(v):
        return np.expm1(v) * 100

    first = len(labels) - len(names)
    rows = []
    for j, name in enumerate(names):
        lo, hi = np.percentile(boots[:, first + j], [2.5, 97.5])
        rows.append(
            {
                "skill": name,
                "family": FAMILY[name],
                "n": int(sk[:, j].sum()),
                "premium_pct": float(pct(coef[first + j])),
                "ci95": [float(pct(lo)), float(pct(hi))],
            }
        )
    rows.sort(key=lambda r: r["premium_pct"], reverse=True)

    gap = boots[:, labels.index("arr_remote")] - boots[:, labels.index("arr_onsite")]
    point = coef[labels.index("arr_remote")] - coef[labels.index("arr_onsite")]
    return {
        "n_postings": int(len(s)),
        "n_companies": int(len(groups)),
        "roles": list(roles),
        "r2_log": float(r2),
        "median_pay_usd": float(s["salary_mid"].median()),
        "skills": rows,
        "remote_vs_onsite_pct": float(pct(point)),
        "remote_vs_onsite_ci95": [
            float(pct(np.percentile(gap, 2.5))),
            float(pct(np.percentile(gap, 97.5))),
        ],
        "n_boot": n_boot,
    }


def fit_pay_model(
    df: pd.DataFrame, roles: tuple[str, ...] = TECH_ROLES, min_n: int = 40, n_folds: int = 5
) -> dict:
    """Log-linear pay model for the estimator, with out-of-fold error bands.

    Same design as `skill_premiums`. Folds are grouped by company so a company's repeated postings
    never sit in both train and test; the 10th/90th percentile of the out-of-fold log errors give
    the band shown around an estimate. Explains only a third of the variance (see `cv_r2_log`).
    """
    from sklearn.model_selection import GroupKFold

    s = df[df["role"].isin(roles) & df["salary_mid"].between(MIN_SALARY, MAX_SALARY)].reset_index(
        drop=True
    )
    skills_all = s["skills_rules"].map(hard_skills)
    counts = skills_all.explode().value_counts()
    names = sorted(counts[counts >= min_n].index)
    X, labels = _design(s, names)
    y = np.log(s["salary_mid"].to_numpy(float))
    company = s["company_name"].fillna("").where(s["company_name"].fillna("") != "", s["job_id"])
    oof = np.empty(len(y))
    folds = GroupKFold(n_splits=n_folds).split(X, y, groups=company.astype(str))
    for train, test in folds:
        oof[test] = X[test] @ np.linalg.lstsq(X[train], y[train], rcond=None)[0]
    resid = y - oof
    coef = np.linalg.lstsq(X, y, rcond=None)[0]
    return {
        "n_postings": int(len(s)),
        "labels": labels,
        "coef": [float(c) for c in coef],
        "roles": sorted(s["role"].unique()),
        "experience": sorted(s["formatted_experience_level"].fillna("Unknown").unique()),
        "arrangements": ["unknown", *ARRANGEMENTS],
        "skills": names,
        "log_error_q10": float(np.percentile(resid, 10)),
        "log_error_q90": float(np.percentile(resid, 90)),
        "cv_mae_usd": float(np.abs(np.exp(oof) - np.exp(y)).mean()),
        "cv_r2_log": float(1 - (resid**2).sum() / ((y - y.mean()) ** 2).sum()),
    }


def predict_pay(
    model: dict, role: str, experience: str, arrangement: str, skills: list[str]
) -> dict[str, float]:
    """Typical annual pay (USD) and an 80% out-of-fold band for one hypothetical posting."""
    x = np.zeros(len(model["labels"]))
    index = {name: i for i, name in enumerate(model["labels"])}
    x[0] = 1.0
    for key in (f"role_{role}", f"exp_{experience}", f"arr_{arrangement}", *skills):
        if key in index:  # baselines (first role, first level, "unknown") have no column
            x[index[key]] = 1.0
    log_pred = float(x @ np.asarray(model["coef"]))
    return {
        "typical": float(np.exp(log_pred)),
        "low": float(np.exp(log_pred + model["log_error_q10"])),
        "high": float(np.exp(log_pred + model["log_error_q90"])),
    }


def sponsor_landscape(
    df: pd.DataFrame, roles: tuple[str, ...] = DATA_ROLES + ("Software Engineer", "Other")
) -> list[dict]:
    """Per role family: how many postings an F-1 / OPT candidate could reasonably pursue."""
    out = []
    for role in roles:
        g = df[df["role"] == role]
        if g.empty:
            continue
        shortlisted = (g["visa_rules"] != "restricted") & (
            (g["visa_rules"] == "friendly") | g["h1b_history"]
        )
        out.append(
            {
                "role": role,
                "postings": int(len(g)),
                "restricted": float((g["visa_rules"] == "restricted").mean()),
                "friendly_text": float((g["visa_rules"] == "friendly").mean()),
                "company_h1b_history": float(g["h1b_history"].mean()),
                "shortlist": float(shortlisted.mean()),
                "entry_or_associate": float(
                    g["formatted_experience_level"].isin(ENTRY_LEVELS).mean()
                ),
            }
        )
    return out


def top_sponsor_employers(
    df: pd.DataFrame, roles: tuple[str, ...] = DATA_ROLES, top: int = 15
) -> list[dict]:
    """Employers with H-1B history that post the most openings in the given role families."""
    g = df[df["role"].isin(roles) & df["h1b_history"] & (df["visa_rules"] != "restricted")]
    grouped = g.groupby("company_name")
    out = pd.DataFrame(
        {
            "openings": grouped.size(),
            "h1b_approvals": grouped["h1b_total"].first(),
            "median_pay_usd": grouped["salary_mid"].median(),
            "friendly_text_openings": grouped["visa_rules"].apply(
                lambda v: int((v == "friendly").sum())
            ),
        }
    )
    out = out.sort_values("openings", ascending=False).head(top).reset_index()
    return json.loads(out.to_json(orient="records"))


def learning_path(
    df: pd.DataFrame,
    role: str,
    levels: tuple[str, ...] | None = ENTRY_LEVELS,
    have: tuple[str, ...] = (),
    steps: int = 8,
    ready_at: float = 0.5,
    min_skills: int = 2,
) -> dict:
    """Greedy order in which to learn skills to qualify for the most postings of a role."""
    sub = df[df["role"] == role]
    if levels is not None:
        sub = sub[sub["formatted_experience_level"].isin(levels)]
    skills = [hard_skills(s) for s in sub["skills_rules"]]
    return learning_path_from_sets(skills, None, role, have, steps, ready_at, min_skills)


def learning_path_from_sets(
    skill_lists: list[list[str]],
    weights: list[float] | None = None,
    role: str = "",
    have: tuple[str, ...] = (),
    steps: int = 8,
    ready_at: float = 0.5,
    min_skills: int = 2,
) -> dict:
    """Same planner on (skill set, count) pairs, so it also runs on the published aggregates.

    A posting counts as "ready" when the candidate has at least `ready_at` of the technical skills
    it lists. Each step adds the skill that makes the most additional postings ready (ties go to
    the more frequent skill). This describes coverage of listed skills, not hiring odds.
    """
    w = np.ones(len(skill_lists)) if weights is None else np.asarray(weights, dtype=float)
    keep = np.array([len(s) >= min_skills for s in skill_lists], dtype=bool)
    skill_lists = [s for s, k in zip(skill_lists, keep, strict=True) if k]
    w = w[keep]
    total = float(w.sum())
    names = sorted({s for lst in skill_lists for s in lst})
    if not names or total == 0:
        return {"role": role, "n_postings": 0, "steps": [], "ready_before": 0.0}
    P = skill_matrix(pd.Series(skill_lists), names)
    need = P.sum(axis=1).astype(float)
    mine = np.array([n in set(have) for n in names])
    covered = P[:, mine].sum(axis=1).astype(float) if mine.any() else np.zeros(len(P))
    freq = (P * w[:, None]).sum(axis=0) / total

    def ready_share(c: np.ndarray) -> float:
        return float((w * (c / need >= ready_at)).sum() / total)

    out = {"role": role, "n_postings": int(round(total)), "ready_before": ready_share(covered)}
    chosen: list[dict] = []
    for _ in range(steps):
        hit = ((covered[:, None] + P) / need[:, None]) >= ready_at
        gain = (hit * w[:, None]).sum(axis=0) / total
        gain[mine] = -1.0
        j = int(np.lexsort((-freq, -gain))[0])
        mine[j] = True
        covered = covered + P[:, j]
        chosen.append(
            {
                "skill": names[j],
                "share_of_postings": float(freq[j]),
                "ready_share": ready_share(covered),
            }
        )
    out["steps"] = chosen
    return out


def compute(df: pd.DataFrame) -> dict:
    res = {
        "n_postings": int(len(df)),
        "premiums": skill_premiums(df),
        "sponsors_by_role": sponsor_landscape(df),
        "top_employers": top_sponsor_employers(df),
        "demand": {
            role: json.loads(
                skill_demand(df, role).reset_index(names="skill").to_json(orient="records")
            )
            for role in DATA_ROLES[:2]
        },
        "learning_path": {role: learning_path(df, role) for role in DATA_ROLES},
    }
    return res


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def findings_markdown(res: dict) -> str:
    """Findings text with every number filled in from `res`; wording says association, not cause."""
    p = res["premiums"]
    sk = {r["skill"]: r for r in p["skills"]}
    sig_up = [r for r in p["skills"] if r["ci95"][0] > 0][:4]
    sig_down = [r for r in p["skills"][::-1] if r["ci95"][1] < 0][:2]
    roles = {r["role"]: r for r in res["sponsors_by_role"]}
    da, other = roles["Data Analyst"], roles["Other"]
    lp = res["learning_path"]["Data Analyst"]
    steps = lp["steps"]
    k = min(5, len(steps))

    def fmt(r: dict) -> str:
        return f"{r['skill']} {r['premium_pct']:+.0f}% ({r['ci95'][0]:+.0f} to {r['ci95'][1]:+.0f})"

    py, ex = sk.get("Python"), sk.get("Excel")
    lines = [
        f"All figures come from {res['n_postings']:,} postings; pay figures use the "
        f"{p['n_postings']:,} data, AI and software postings that state a salary "
        f"({p['n_companies']:,} companies, median ${p['median_pay_usd']:,.0f}). Pay comparisons "
        "are adjusted for role, experience level and work arrangement and are associations, "
        "not causal effects.",
        "",
        "**1. Which skills go with higher pay.** After adjusting, the skills most associated with "
        "higher pay are "
        + ", ".join(fmt(r) for r in sig_up)
        + " (95% interval in brackets). "
        + (
            f"Python itself shows {py['premium_pct']:+.0f}% ({py['ci95'][0]:+.0f} to "
            f"{py['ci95'][1]:+.0f}) because it is listed so widely that it does not separate "
            "higher- from lower-paid postings. "
            if py
            else ""
        )
        + (
            f"Excel is associated with {ex['premium_pct']:+.0f}% "
            f"({ex['ci95'][0]:+.0f} to {ex['ci95'][1]:+.0f}). "
            if ex
            else ""
        )
        + (
            "Lower for "
            + " and ".join(f"{r['skill']} ({r['premium_pct']:+.0f}%)" for r in sig_down)
            + "."
            if sig_down
            else ""
        ),
        "",
        "![Skill pay association](docs/figures/skill_premium.png)",
        "",
        f"**2. Remote pays no clearly different amount.** Remote postings are "
        f"{p['remote_vs_onsite_pct']:+.1f}% vs onsite ({p['remote_vs_onsite_ci95'][0]:+.1f} to "
        f"{p['remote_vs_onsite_ci95'][1]:+.1f}) after the same adjustment; the interval includes "
        "zero, so the data cannot separate a remote premium from no difference.",
        "",
        "**3. More data postings pass a sponsorship screen than the average posting.** "
        f"{_pct(da['shortlist'])} of Data Analyst postings are not restricted and either say "
        "sponsorship is possible or come from a company with H-1B approvals in FY2021-23, "
        f"against {_pct(other['shortlist'])} of other postings. Only {_pct(da['restricted'])} of "
        f"Data Analyst postings rule sponsorship out and only {_pct(da['friendly_text'])} say it "
        "is offered, so for most the signal is the company's history, not the posting. That "
        "history says a company files petitions, not that this role would.",
        "",
        "![Sponsor share by role](docs/figures/sponsor_share.png)",
        "",
        "![Employers](docs/figures/top_employers.png)",
        "",
        "_Approval counts cover only the legal-entity names the company matched to, so parent "
        "companies whose petitions are filed under other names are undercounted (see "
        "Limitations)._",
        "",
        f"**4. Data roles skew senior.** {_pct(da['entry_or_associate'])} of Data Analyst "
        f"postings are entry-level, associate or internship, against "
        f"{_pct(other['entry_or_associate'])} of other postings, so entry-level data jobs are a "
        "smaller pool to search.",
        "",
        "![Data analyst skills](docs/figures/data_analyst_skills.png)",
        "",
        f"**5. What to learn first.** Across {lp['n_postings']} entry-level Data Analyst postings "
        f"that list at least two technical skills, learning "
        + ", ".join(s["skill"] for s in steps[:k])
        + f" in that order gets you to at least half of the listed skills in "
        f"{_pct(steps[k - 1]['ready_share'])} of them (from {_pct(lp['ready_before'])} with none). "
        "Order is chosen greedily and describes skill overlap with postings, not hiring odds. "
        "The dashboard has the same planner for your own skill set.",
        "",
        "![Learning path](docs/figures/learning_path.png)",
    ]
    return "\n".join(lines)


def run(path: Path = INSIGHTS_JSON, figures: bool = True) -> dict:
    from .report import DASHBOARD_PARQUET, MARK_END_FINDINGS, MARK_START_FINDINGS, README

    if not DASHBOARD_PARQUET.is_file():
        raise SystemExit("Run `jobinsights report` first.")
    df = pd.read_parquet(DASHBOARD_PARQUET)
    res = compute(df)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(res, indent=2), encoding="utf-8")
    text = findings_markdown(res)
    (OUT_DIR / "FINDINGS.md").write_text(text, encoding="utf-8")
    if figures:
        from . import plots

        plots.draw_all(res)
    if README.is_file():
        body = README.read_text(encoding="utf-8")
        if MARK_START_FINDINGS in body and MARK_END_FINDINGS in body:
            head, rest = body.split(MARK_START_FINDINGS, 1)
            _, tail = rest.split(MARK_END_FINDINGS, 1)
            block = f"{head}{MARK_START_FINDINGS}\n{text}\n{MARK_END_FINDINGS}{tail}"
            README.write_text(block, encoding="utf-8")
    print(f"insights -> {path}")
    return res
